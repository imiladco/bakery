<?php

declare(strict_types=1);

namespace Bakery_Credit\Domain;

/**
 * موجودی اعتبار یک کاربر در یک دورهٔ مشخص: سقف، مصرف، و باقی‌مانده.
 *
 * ⚠️ این کلاس مرجع تصمیمِ «آیا این خرید مجاز است؟» نیست.
 *
 * تصمیم قطعیِ خرید داخل یک دستور اتمیک SQL گرفته می‌شود
 * (Storage\Ledger::tryDebit). دلیلش سناریوی خرید همزمان است: اگر
 * کاربری با اعتبار ۱۰۰ دو سفارش ۶۰ تایی را از دو تب هم‌زمان بفرستد،
 * هر دو درخواست این‌جا «کافی است» می‌گیرند و ۱۲۰ خرج می‌شود. تنها
 * دفاع، سنجیدنِ موجودی در همان دستوری‌ست که کسر را ثبت می‌کند.
 *
 * پس نقش این کلاس فقط نمایش و پیش‌چکِ نرم است: عددی که در سایدبار سبد
 * دیده می‌شود، و سقفی که دکمهٔ + را خاموش می‌کند. اگر روزی کسی خواست
 * مرجعِ تصمیم را به این‌جا بیاورد، همین یادداشت جلویش را بگیرد.
 *
 * دربارهٔ float: مبالغ تومان عدد صحیح‌اند و اعداد صحیح تا ۲^۵۳ در
 * float64 دقیقاً نمایش داده می‌شوند، پس در محدودهٔ واقعی خطای گردکردن
 * وجود ندارد. جمع و مقایسهٔ مرجع هم که اصلاً این‌جا نیست، در MySQL روی
 * DECIMAL انجام می‌شود.
 */
final class Balance
{
    public function __construct(
        public readonly Period $period,
        public readonly float $allowance,
        public readonly float $consumed,
    ) {
    }

    /**
     * باقی‌مانده، هرگز منفی.
     *
     * منفی‌شدن یک حالت واقعی‌ست، نه فرضی: ادمین می‌تواند وسط ماه سقف را
     * بیاورد زیر چیزی که کاربر همان ماه خرج کرده. آن سفارش‌ها انجام
     * شده‌اند و پس گرفته نمی‌شوند؛ فقط از این به بعد چیزی برای خرج
     * نمانده. clamp روی صفر همین را می‌گوید، و مهم‌تر اینکه این کسری
     * به‌عنوان بدهی به ماه بعد منتقل نمی‌شود — «عدم انتقال» در هر دو
     * جهت برقرار است، هم مانده و هم بدهی.
     */
    public function remaining(): float
    {
        return max(0.0, $this->allowance - $this->consumed);
    }

    public function canAfford(float $amount): bool
    {
        return $amount > 0.0 && $amount <= $this->remaining();
    }

    /** سقف تعریف‌نشده (صفر) و سقفِ تمام‌شده هر دو این‌جا true می‌دهند. */
    public function isExhausted(): bool
    {
        return $this->remaining() <= 0.0;
    }

    /**
     * بیشترین تعداد از کالایی با این قیمت که اعتبار کفافش را می‌دهد.
     *
     * همان عددی که سقف دومِ دکمهٔ + می‌شود: ویجت افزودن به سبد از قبل یک
     * سقف دارد (موجودی انبار) و این کنارش می‌نشیند، پس کاربر اصلاً
     * نمی‌تواند سبدی بسازد که از پسش برنیاید.
     */
    public function affordableUnits(float $unitPrice): int
    {
        if ($unitPrice <= 0.0) {
            return 0;
        }

        return (int) floor($this->remaining() / $unitPrice);
    }
}
