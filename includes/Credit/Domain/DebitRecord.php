namespace Bakery_Credit\Domain;

/**
 * سطرِ کسرِ یک سفارش، همان‌طور که در دفتر ثبت شده.
 *
 * چرا این کلاس لازم شد: برگشت اعتبار قبلاً چهار چیز را از خودِ سفارش
 * ووکامرس حدس می‌زد — اینکه اصلاً با اعتبار پرداخت شده (از روی
 * payment_method)، مالکش کیست (customer_id)، چقدر بوده (get_total)، و
 * به کدام ماه برگردد (تاریخ ساخت سفارش). هر چهارتا می‌توانند بعد از
 * پرداخت عوض شوند: ادمین روش پرداخت را در صفحهٔ سفارش دست بزند، مبلغ را
 * ویرایش کند، یا سفارش را ماه بعد لغو کند. آن‌وقت برگشت اعتبار یا
 * اصلاً انجام نمی‌شد یا عدد اشتباه را به ماه اشتباه برمی‌گرداند.
 *
 * حقیقتِ «چقدر از اعتبار چه کسی در کدام دوره کم شد» یک‌جا ثبت شده و آن
 * خودِ دفتر است. پس برگشت از همان‌جا خوانده می‌شود، نه از سفارش.
 */
final class DebitRecord
{
    public function __construct(
        public readonly int $userId,
        public readonly string $periodKey,
        public readonly float $amount,
    ) {
    }
}
