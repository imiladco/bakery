/**
 * عدد «موجودی» — یک جا خوانده می‌شود و یک جا قالب‌بندی.
 *
 * سه ویجت این عدد را نشان می‌دهند (نوار حساب کاربری، هدر، سایدبار سبد)
 * و بعد از هر ثبت سفارش باید همان لحظه درست شود، نه بعد از رفرش. برای
 * همین دو مصرف دارد که باید دقیقاً یک رشته بدهند:
 *
 *   - رندر اولیهٔ ویجت (Traits\Account_Actions_Controls)
 *   - فرگمنت AJAX بعد از ثبت سفارش (Cart_Fragments)
 *
 * اگر هرکدام قالب‌بندی خودش را داشت، عددی که بعد از خرید جای عدد قبلی
 * می‌نشیند می‌توانست شکل دیگری داشته باشد — ارقام لاتین به‌جای فارسی،
 * یا جداکنندهٔ متفاوت.
 *
 * عمداً به ووکامرس وابسته نیست: نوار حساب کاربری روی سایتی بدون
 * ووکامرس هم رندر می‌شود، در حالی که Cart_Fragments اصلاً بارگذاری
 * نمی‌شود.
 */
final class Account_Balance
{
    /** عنصری که فرگمنت جایگزینش می‌کند. */
    public const SELECTOR = '[data-bkw-account-balance]';

    /**
     * عدد موجودی، بدون برچسب و بدون واحد پول.
     *
     * $fallback مقدار فرضیِ تب محتوای ویجت است، برای نصبی که ماژول
     * اعتبار رویش فعال نیست. در مسیر AJAX چنین مقداری در دسترس نیست و
     * صفر می‌ماند — بی‌اهمیت، چون بدون آن ماژول اصلاً پرداختی انجام
     * نمی‌شود که موجودی تغییر کند.
     */
    public static function amount(int $user_id, float $fallback = 0.0): string
    {
        $balance = (float) apply_filters('bkw_account_balance', $fallback, $user_id);

        return self::persian_digits(number_format($balance, 0, '.', ','));
    }

    /**
     * همان عدد، داخل عنصری که فرگمنت هدفش می‌گیرد.
     *
     * این span عمداً هیچ کلاسی ندارد و تو در توی span‌های استایل‌دار
     * می‌نشیند. دلیلش این است که دو چیدمان نوار حساب («کامل» و
     * «فشرده») استایل‌های متفاوتی روی خودِ عدد دارند؛ اگر فرگمنت
     * عنصرِ استایل‌دار را جایگزین می‌کرد، یک HTML ثابت باید هر دو را
     * راضی می‌کرد و یکی‌شان ظاهرش عوض می‌شد. این‌طور فرگمنت فقط متن را
     * عوض می‌کند و استایل هر چیدمان دست‌نخورده از والدش می‌آید.
     */
    public static function fragment_html(int $user_id, float $fallback = 0.0): string
    {
        return sprintf(
            '<span %s>%s</span>',
            // سلکتور، attribute-selector است ([data-x])؛ برای درج در
            // خودِ مارک‌آپ باید بدون کروشه بیاید.
            trim(self::SELECTOR, '[]'),
            esc_html(self::amount($user_id, $fallback))
        );
    }

    private static function persian_digits(string $value): string
    {
        return strtr($value, [
            '0' => '۰', '1' => '۱', '2' => '۲', '3' => '۳', '4' => '۴',
            '5' => '۵', '6' => '۶', '7' => '۷', '8' => '۸', '9' => '۹',
        ]);
    }
}
